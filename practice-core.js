// เฟรมที่ 30fps: ขึ้น/ลง (Tour Tempo) · ลูกเต็มวง 3:1 · ลูกสั้น 2:1
export const TEMPOS = [[18, 6, 'เร็ว'], [21, 7, 'กลาง'], [24, 8, 'ช้า'], [27, 9, 'ช้ามาก']];
export const TEMPOS_SHORT = [[14, 7, 'เร็ว'], [16, 8, 'กลาง'], [18, 9, 'ช้า']];
// จังหวะจากคลิปที่ติดป้าย ตั้งท่า/ขึ้นสุด/กระทบ (วินาทีจริง = วินาทีในคลิป / ตัวคูณสโลว์)
export function tempoOf(tags, slow = 1) {
  if (!tags || tags.a == null || tags.top == null || tags.imp == null) return null;
  const bs = (tags.top - tags.a) / (slow || 1), ds = (tags.imp - tags.top) / (slow || 1);
  if (bs <= 0 || ds <= 0) return null;
  return { bs, ds, ratio: bs / ds };
}
export function nearestTempo(bs) { return TEMPOS.reduce((b, x) => Math.abs(x[0] / 30 - bs) < Math.abs(b[0] / 30 - bs) ? x : b); }

// คำแนะนำตามรูปแบบที่พลาดบ่อย (ในเซสชันเดียวกัน อย่างน้อย 5 ลูก)
export function rangeTip(s) {
  if (!s || s.n < 5) return null;
  const miss = s.fat + s.thin + s.wild, nd = s.L + s.C + s.R;
  if (s.fat >= 2 && s.fat >= s.thin && s.fat >= s.wild) return ['⬇️', 'ตีดินบ่อย: หัวไม้ลงพื้นก่อนถึงลูก', 'ย้ายน้ำหนักไปเท้าหน้ามากขึ้น (55-60%) ตั้งแต่ตั้งท่า · เช็คว่าลูกไม่ค่อนเท้าหน้าเกิน · ลองแบบฝึก "เส้นจุดต่ำสุด"'];
  if (s.thin >= 2 && s.thin >= s.wild) return ['⬆️', 'ท็อป/บางบ่อย: หัวไม้ยังไม่ลงถึงพื้น', 'อย่าพยายามช้อนลูกขึ้น ให้สับลงหลังลูก · รักษามุมก้มตัวจนผ่านลูก · ลดวงเหลือ ¾ จนคอนแทคกลับมา'];
  if (s.wild >= 2) return ['🌀', 'ลูกหลุดแรงบ่อย', 'ลดแรงเหลือ 80% แล้วใช้ "จังหวะสวิง" · เช็คว่าแนวเท้า สะโพก ไหล่ ขนานกับแนวเป้า (วางไม้บนพื้นช่วยเล็ง)'];
  if (nd >= 5 && s.R / nd >= 0.5) return ['↗️', 'ลูกออกขวาบ่อย', 'มักเป็นหน้าไม้เปิดตอนกระทบ · ลองหมุนกริปมือซ้ายให้เห็นข้อนิ้ว 2-3 ข้อ · เช็คว่าไหล่ไม่เปิด และลูกไม่ค่อนเท้าหน้าเกิน'];
  if (nd >= 5 && s.L / nd >= 0.5) return ['↖️', 'ลูกออกซ้ายบ่อย', 'มักเป็นหน้าไม้ปิดหรือไหล่ปิด · ผ่อนกริปลงนิด · เช็คแนวไหล่ขนานเป้า · ลูกอาจค่อนเท้าหลังเกิน'];
  if (miss / s.n <= 0.2 && s.n >= 8) return ['✅', 'คอนแทคดีมาก', 'ท่าตั้งตอนนี้คือ "จุดพอดี" ของไม้นี้ · บันทึกไว้ใน "จุดตั้งแต่ละไม้" แล้วอัดคลิปเก็บเป็นวงต้นแบบ ⭐'];
  return null;
}
