export function setupKey(c) {
  if (c === 'D') return 'D'; if (/W$/.test(c)) return 'FW'; if (/H$/.test(c)) return 'HY'; if (c === 'Putter') return 'PUTT';
  const n = parseInt(c); if (/i$/.test(c)) return n <= 5 ? 'LI' : n <= 7 ? 'MI' : 'SI';
  return isWedge(c) ? 'W' : 'MI';
}

