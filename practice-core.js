export const MISS = ['fat', 'thin', 'wild'];

const median = a => { if (!a.length) return null; const s = [...a].sort((x, y) => x - y), m = s.length >> 1; return s.length % 2 ? s[m] : (s[m - 1] + s[m]) / 2; };
const quant = (a, q) => { if (!a.length) return null; const s = [...a].sort((x, y) => x - y), p = (s.length - 1) * q, lo = Math.floor(p), hi = Math.ceil(p); return s[lo] + (s[hi] - s[lo]) * (p - lo); };

// สถิติของลูกกลุ่มหนึ่ง (ไม้เดียวกัน / วงสวิงเดียวกัน)
// คะแนนคงที่ = เต็มหน้าไม้ 1 + พอใช้ 0.5 ต่อลูก → ร้อยละ · ระยะ = มัธยฐานของลูกเต็มหน้าไม้ (ไม่มีก็ใช้ลูกพอใช้)
export function groupStats(balls) {
  const o = { n: balls.length, p: 0, o: 0, fat: 0, thin: 0, wild: 0, L: 0, C: 0, R: 0, dp: [], dok: [] };
  balls.forEach(b => { o[b.q] = (o[b.q] || 0) + 1; if (b.q === 'p' || b.q === 'o') { if (b.dir) o[b.dir]++; if (b.d != null) (b.q === 'p' ? o.dp : o.dok).push(b.d); } });
  const ds = o.dp.length >= 2 || !o.dok.length ? o.dp : o.dp.concat(o.dok);
  o.score = o.n ? Math.round((o.p + o.o * 0.5) / o.n * 100) : null;
  o.solid = o.n ? Math.round((o.p + o.o) / o.n * 100) : null;
  const nd = o.L + o.C + o.R; o.straight = nd ? Math.round(o.C / nd * 100) : null;
  o.carry = median(ds); o.lo = quant(ds, .25); o.hi = quant(ds, .75); o.nd = ds.length;
  o.miss = MISS.map(k => [k, o[k]]).filter(x => x[1]).sort((a, b) => b[1] - a[1])[0]?.[0] || null; // พลาดแบบไหนบ่อยสุด
  return o;
}
export const keyOf = b => b.c + (isWedge(b.c) && b.sw && b.sw !== 'full' ? '|' + b.sw : '');

// ตารางระยะไม้ (วงเต็ม) + ช่องว่างระหว่างไม้ที่ติดกัน
export function bagTable(balls, bag) {
  const by = {}; balls.forEach(b => { if (b.sw && b.sw !== 'full') return; (by[b.c] = by[b.c] || []).push(b); });
  const clubs = [...new Set([...(bag || []), ...Object.keys(by)])].filter(c => c !== 'Putter').sort((a, b) => clubIx(a) - clubIx(b));
  const rows = clubs.map(c => ({ c, s: groupStats(by[c] || []) }));
  let prev = null;
  rows.forEach(r => { r.gap = null; r.warn = null; if (r.s.carry == null || r.s.nd < 3) return;
    if (prev) { r.gap = prev.s.carry - r.s.carry; if (r.gap < 6) r.warn = 'close'; else if (r.gap > 22) r.warn = 'wide'; }
    prev = r; });
  return rows;
}
// ตารางเวดจ์ × วงสวิง (ระบบนาฬิกา)
export function wedgeMatrix(balls, bag) {
  const ws = [...new Set([...(bag || []).filter(isWedge), ...balls.filter(b => isWedge(b.c)).map(b => b.c)])].sort((a, b) => clubIx(a) - clubIx(b));
  return ws.map(c => ({ c, cells: SWINGS.map(([s]) => groupStats(balls.filter(b => b.c === c && (b.sw || 'full') === s))) }));
}
// แนวโน้มความคงที่ของไม้หนึ่งต่อเซสชัน (เฉพาะเซสชันที่ตีอย่างน้อย 5 ลูก)
export function clubTrend(balls, key) {
  const by = {}; balls.filter(b => keyOf(b) === key).forEach(b => { (by[b.s] = by[b.s] || []).push(b); });
  return Object.entries(by).filter(([, a]) => a.length >= 5).map(([s, a]) => ({ s: +s, ...groupStats(a) })).sort((a, b) => a.s - b.s);
}
export function sessions(balls) {
  const by = {}; balls.forEach(b => { (by[b.s] = by[b.s] || []).push(b); });
  return Object.entries(by).map(([s, a]) => ({ s: +s, n: a.length, clubs: [...new Set(a.map(b => b.c))].sort((x, y) => clubIx(x) - clubIx(y)), st: groupStats(a) })).sort((a, b) => b.s - a.s);
}

// ระยะเฉลี่ยในสนามจริงจาก GPS (ประวัติรอบ ชื่อผู้เล่นเดียวกัน) — เมตร
export function courseDistances(hist, name) {
  const m = {};
  (hist || []).forEach(r => { const p = r.rp?.players?.find(x => x.name?.trim() === name); if (!p) return;
    Object.values(r.rp.shots?.[p.id] || {}).forEach(hs => {
      const s = Object.values(hs || {}).filter(x => x.lat != null).sort((a, b) => a.t - b.t);
      s.forEach((x, k) => { const nx = s[k + 1]; if (!nx || !x.club || x.club === 'Putter') return; const d = dist([x.lat, x.lng], [nx.lat, nx.lng]); if (d >= 3 && d < 350) (m[x.club] = m[x.club] || []).push(d); });
    }); });
  const o = {}; for (const c in m) o[c] = { n: m[c].length, d: median(m[c]) };
  return o;
}

